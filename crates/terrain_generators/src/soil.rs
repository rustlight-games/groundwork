    #[test]
    fn a_tile_is_a_pure_function_of_where_it_is() {
        // Two surfaces built independently must agree everywhere, or a plate
        // traced in slices grows seams down the joins between them.
        let a = SoilSurface::new(loam(), 0x51_11);
        let b = SoilSurface::new(loam(), 0x51_11);
        for i in 0..40 {
            let p = Vec2::new(i as f32 * 0.137 - 2.0, i as f32 * -0.211 + 1.3);
            let (x, y) = (a.height(p, 0.4, 0.6), b.height(p, 0.4, 0.6));
            assert_eq!(x, y, "at {p:?}");
        }
    }

    #[test]
    fn the_halo_is_wide_enough_that_the_interior_has_settled() {
        // The claim `HALO_CELLS` rests on: transport into a tile's interior dies
        // out well before the halo's edge, so a wider halo changes nothing. If
        // this fails the halo is too narrow and tiles disagree at their joins —
        // which is the one failure this whole tiling scheme has to avoid.
        let surface = SoilSurface::new(loam(), 0xA11_0);
        let narrow = surface.simulate((0, 0), 0.4, 0.6, HALO_CELLS);
        let wide = surface.simulate((0, 0), 0.4, 0.6, HALO_CELLS * 2);
        let differences: Vec<f32> = narrow
            .height
            .iter()
            .zip(&wide.height)
            .map(|(a, b)| (a - b).abs())
            .collect();
        let moved = differences.iter().filter(|d| **d > 0.0).count();
        let worst = differences.iter().copied().fold(0.0f32, f32::max);

        // ## Almost every cell is bit-identical, and a couple are not
        //
        // Coordinates are anchored to the tile rather than to the grid, so the
        // same world point is computed by the same sum whatever the halo — see
        // `Grid::origin`. That makes the great majority of the interior agree
        // exactly rather than merely closely.
        //
        // A handful of cells still differ, and the reason is inherent rather
        // than fixable. The slump has a *threshold* in it: material moves or it
        // does not. A cell sitting within a hair of that threshold can be tipped
        // either way by the last-place difference in a neighbour arriving from
        // further out, and a hundred and eighty passes then amplify the choice.
        // Two cells in sixty-three thousand, by under a millimetre, on relief
        // measured in centimetres.
        //
        // What this test therefore claims is that the halo is wide enough for
        // the interior to have settled, not that a chaotic iteration is
        // reproducible across two different amounts of surrounding ground. The
        // guarantee that tiles agree *with each other* is the next test, and it
        // is the one seams actually depend on.
        assert!(
            moved * 200 < differences.len(),
            "{moved} of {} cells moved when the halo doubled",
            differences.len()
        );
        assert!(worst < 1.5e-3, "doubling the halo moved a cell by {worst} m");
    }

    #[test]
    fn neighbouring_tiles_agree_across_their_join() {
        // The same test from the sampling side. A point just inside one tile and
        // a point just inside the next must describe one continuous surface.
        // Sampled densely along a whole join, and across both axes, because a
        // seam is a line rather than a point and one bad cell on it is a visible
        // crack running the height of a plate.
        let surface = SoilSurface::new(loam(), 0x_10_1D);
        let mut worst = 0.0f32;
        for i in 0..500 {
            let t = -1.0 + i as f32 * 0.004;
            for (a, b) in [
                (
                    Vec2::new(TILE_M - 1.0e-4, t),
                    Vec2::new(TILE_M + 1.0e-4, t),
                ),
                (
                    Vec2::new(t, TILE_M - 1.0e-4),
                    Vec2::new(t, TILE_M + 1.0e-4),
                ),
            ] {
                let step = (surface.height(a, 0.4, 0.6) - surface.height(b, 0.4, 0.6)).abs();
                worst = worst.max(step);
            }
        }
        // ## What this bounds, and what it does not
        //
        // Measured at half a millimetre over a thousand samples of two full
        // joins, against centimetres of relief either side. A traced pixel at
        // this project's resolution is 3.1 mm, so the seam is a sixth of one and
        // cannot be resolved even in principle.
        //
        // It is not zero, and chasing it to zero would be chasing the wrong
        // thing. The slump has a threshold in it and two tiles see different
        // ground beyond their halos, so a cell sitting within a hair of that
        // threshold can fall either way — see the previous test. The figure also
        // rises as the surface gains variation, which is why it moved from a
        // third of a millimetre to a half when the events started varying in
        // density: more relief, more cells near the threshold.
        //
        // What this test is for is *structural* seams. It is the test that
        // caught tiles storing one sample too few, which put a cell-wide gap
        // between neighbours and stepped the join by **seventeen millimetres** —
        // thirty times this bound, and plainly visible as a crack running the
        // height of a plate.
        assert!(worst < 1.0e-3, "the join steps by {worst} m");
    }

    #[test]
    fn the_surface_is_not_the_same_everywhere() {
        // The defect this module exists for. Procedural noise is statistically
        // uniform: every patch has the same distribution as every other, which
        // is why a metre of it reads as one texture tiled. A surface with a
        // history does not — some of it was worked over, some was left alone.
        //
        // Measured as the spread of per-patch roughness across a plate. A noise
        // field's is near zero by construction.
        let surface = SoilSurface::new(loam(), 0x5EED);
        let mut patches = Vec::new();
        for py in 0..4 {
            for px in 0..4 {
                let mut values = Vec::new();
                for i in 0..24 {
                    for j in 0..24 {
                        values.push(surface.height(
                            Vec2::new(
                                px as f32 * 0.25 + i as f32 * 0.01,
                                py as f32 * 0.25 + j as f32 * 0.01,
                            ),
                            0.4,
                            0.6,
                        ));
                    }
                }
                let mean = values.iter().sum::<f32>() / values.len() as f32;
                let variance = values.iter().map(|v| (v - mean).powi(2)).sum::<f32>()
                    / values.len() as f32;
                patches.push(variance.sqrt());
            }
        }
        let mean = patches.iter().sum::<f32>() / patches.len() as f32;
        let spread = patches
            .iter()
            .map(|p| (p - mean).abs())
            .fold(0.0f32, f32::max);
        assert!(
            spread / mean > 0.25,
            "every patch has the same roughness ({mean:.5} +/- {spread:.5}); \
             the surface is statistically uniform and will read as tiled noise"
        );
    }

    #[test]
    fn the_ground_can_shadow_itself() {
        // The sun is at 35 degrees, so a face has to tilt past 35 before it
        // falls into its own shadow. A noise-based surface never did, at any
        // moisture, anywhere — which is why every apparent feature on it was
        // pigment rather than form.
        let surface = SoilSurface::new(loam(), 0x_5AD5);
        let step = 0.004;
        let mut steep = 0;
        let mut total = 0;
        for i in 0..200 {
            for j in 0..200 {
                let p = Vec2::new(i as f32 * step, j as f32 * step);
                let h = surface.height(p, 0.4, 0.6);
                let dx = (surface.height(p + Vec2::new(step, 0.0), 0.4, 0.6) - h) / step;
                let dy = (surface.height(p + Vec2::new(0.0, step), 0.4, 0.6) - h) / step;
                total += 1;
                if dx.hypot(dy) > 35.0f32.to_radians().tan() {
                    steep += 1;
                }
            }
        }
        let share = steep as f32 / total as f32;
        assert!(
            share > 0.02,
            "only {:.2}% of the surface can shadow at a 35-degree sun",
            share * 100.0
        );
    }
