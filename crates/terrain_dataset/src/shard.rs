//! One shard: two renders of one meadow, and everything that produced them.
//!
//! ## The API makes the wrong thing hard to write
//!
//! [`RenderPair`] holds an `Arc<TerrainScene>` and hands the *same* one to both
//! renderers. There is no constructor that takes two scenes and no function here
//! that takes two generators, which is the whole point: the failure this
//! prevents is silent.
//!
//! ```text
//!   wrong                              right
//!   ─────                              ─────
//!   cheap  → generate scene A          generate scene ────┬─→ render cheap
//!   costly → generate scene B                             └─→ render costly
//! ```
//!
//! Generating twice would agree today, because placement is a pure function of
//! world position. It is not today's agreement that matters; it is that nothing
//! can *later* make them disagree. A quality tier that skips a fork, a rib count
//! that moves a vertex, an optimisation that reorders a draw — any of those turns
//! the pair into two photographs of two different fields, and a network trained
//! on that learns to hallucinate rather than to reconstruct. The loss simply
//! stops falling and no image in the corpus looks wrong.
//!
//! ## The manifest pins everything
//!
//! A corpus that cannot say what produced it can only be regenerated by
//! guessing, and a renderer under active development does not produce the same
//! bytes next month. That is not a provenance nicety: a model whose targets came
//! from two renderer versions has learned the average of two looks, and nothing
//! in the loss curve says so.
//!
//! So a shard records the document digest, the scene fingerprint, the seed, the
//! bounds, the camera, the pixel scale, both renderer versions, the Blender
//! version, the render settings, the crop margin, the pass list, and a checksum
//! per file. Every one of those has a specific failure behind it.

use std::sync::Arc;

use terrain_core::coords::WorldRect;
use terrain_core::digest::{Digest, Fingerprint};
use terrain_scene::scene::TerrainScene;

/// One renderer's output.
#[derive(Clone, Debug)]
pub struct RenderArtifact {
    /// Which renderer produced it.
    pub renderer: String,
    /// That renderer's version.
    pub version: String,
    /// The files it wrote, relative to the shard's directory.
    pub files: Vec<ArtifactFile>,
}

/// One file in a shard.
#[derive(Clone, Debug)]
pub struct ArtifactFile {
    /// Which channel this is: `beauty`, `albedo`, `elevation`.
    pub pass: String,
    pub path: String,
    pub bytes: usize,
    /// A checksum, so a truncated write is an error rather than a black frame.
    pub checksum: Fingerprint,
}

/// A cheap render and an expensive one, of one scene.
///
/// The `Arc` is the point. Both renderers are handed the same scene by
/// reference, and there is no way to construct this from two.
pub struct RenderPair {
    scene: Arc<TerrainScene>,
    pub input: RenderArtifact,
    pub target: RenderArtifact,
}

impl RenderPair {
    /// Build a pair from one scene.
    ///
    /// The renderers are closures rather than values so that the scene can be
    /// passed to each by reference without either taking ownership — which is
    /// the mechanical enforcement of "one meadow" rather than a documented rule.
    pub fn render(
        scene: Arc<TerrainScene>,
        input: impl FnOnce(&TerrainScene) -> RenderArtifact,
        target: impl FnOnce(&TerrainScene) -> RenderArtifact,
    ) -> Self {
        let cheap = input(&scene);
        let costly = target(&scene);
        Self {
            scene,
            input: cheap,
            target: costly,
        }
    }

    pub fn scene(&self) -> &TerrainScene {
        &self.scene
    }

    /// The fingerprint both halves share.
    ///
    /// One value, because there is one scene. A pair whose halves could report
    /// different fingerprints would be a pair that had already gone wrong.
    pub fn scene_fingerprint(&self) -> Fingerprint {
        self.scene.fingerprint()
    }
}

/// The version this build writes.
pub const SHARD_MANIFEST_VERSION: u32 = 1;

/// Everything needed to reproduce a shard.
#[derive(Clone, Debug)]
pub struct ShardManifest {
    pub manifest_version: u32,
    pub shard: usize,
    /// The terrain document this came from.
    pub document_digest: Fingerprint,
    /// The scene both renders saw.
    pub scene_fingerprint: Fingerprint,
    pub root_seed: u64,
    pub bounds: WorldRect,
    pub pixels_per_metre: f32,
    /// The camera's own digest, so two shards framed differently are
    /// distinguishable without comparing floats.
    pub camera_digest: Fingerprint,
    pub input: RenderArtifact,
    pub target: RenderArtifact,
    /// Which Blender produced the target.
    pub blender_version: String,
    /// The render profile's digest.
    pub render_profile_digest: Fingerprint,
    /// Every recipe that contributed, and its version.
    pub recipe_versions: Vec<(String, u32)>,
    /// Texels trimmed from each edge.
    ///
    /// Not decoration. Every neighbourhood-reading term in the cheap renderer is
    /// wrong near an edge, so a corpus of crops baked at their own size teaches
    /// a network that borders exist — and it will faithfully reproduce them.
    pub crop_margin: u32,
    /// How many marks the shared scene held.
    ///
    /// Worth recording: a crop grown from a nearly empty scene is not a hard
    /// example, it is a useless one, and a corpus with a hundred of them has a
    /// hundred fewer shards than its directory listing suggests.
    pub marks: usize,
}

impl ShardManifest {
    /// A digest of everything that decides the shard's content.
    pub fn digest(&self) -> Fingerprint {
        let mut digest = Digest::for_domain("terrain-dataset-shard");
        digest
            .u32(self.manifest_version)
            .digest(self.document_digest)
            .digest(self.scene_fingerprint)
            .u64(self.root_seed)
            .f64(self.bounds.min.u_m)
            .f64(self.bounds.min.v_m)
            .f64(self.bounds.max.u_m)
            .f64(self.bounds.max.v_m)
            .f32(self.pixels_per_metre)
            .digest(self.camera_digest)
            .str(&self.input.renderer)
            .str(&self.input.version)
            .str(&self.target.renderer)
            .str(&self.target.version)
            .str(&self.blender_version)
            .digest(self.render_profile_digest)
            .u32(self.crop_margin);
        digest.slice(&self.recipe_versions, |d, (key, version)| {
            d.str(key).u32(*version);
        });
        digest.finish()
    }

    /// Serialise as RON, which is what this repository stores data in.
    pub fn to_ron(&self) -> String {
        let files = |artifact: &RenderArtifact| -> String {
            artifact
                .files
                .iter()
                .map(|file| {
                    format!(
                        "            (pass: \"{}\", path: \"{}\", bytes: {}, checksum: \"{}\"),",
                        file.pass, file.path, file.bytes, file.checksum
                    )
                })
                .collect::<Vec<_>>()
                .join("\n")
        };
        let recipes = self
            .recipe_versions
            .iter()
            .map(|(key, version)| format!("        (\"{key}\", {version}),"))
            .collect::<Vec<_>>()
            .join("\n");

        format!(
            "// One shard: two renders of one meadow.\n\
             //\n\
             // Everything here is pinned so the shard can be reproduced rather than\n\
             // guessed at. A model whose targets came from two renderer versions has\n\
             // learned the average of two looks, and nothing in a loss curve says so.\n\
             (\n\
             \x20   manifest_version: {},\n\
             \x20   shard: {},\n\
             \x20   document_digest: \"{}\",\n\
             \x20   scene_fingerprint: \"{}\",\n\
             \x20   root_seed: \"{:016x}\",\n\
             \x20   bounds: (min: ({:.4}, {:.4}), max: ({:.4}, {:.4})),\n\
             \x20   pixels_per_metre: {},\n\
             \x20   camera_digest: \"{}\",\n\
             \x20   marks: {},\n\
             \x20   crop_margin: {},\n\
             \x20   blender_version: \"{}\",\n\
             \x20   render_profile_digest: \"{}\",\n\
             \x20   recipe_versions: [\n{}\n    ],\n\
             \x20   input: (\n\
             \x20       renderer: \"{}\",\n\
             \x20       version: \"{}\",\n\
             \x20       files: [\n{}\n        ],\n    ),\n\
             \x20   target: (\n\
             \x20       renderer: \"{}\",\n\
             \x20       version: \"{}\",\n\
             \x20       files: [\n{}\n        ],\n    ),\n\
             \x20   manifest_digest: \"{}\",\n)\n",
            self.manifest_version,
            self.shard,
            self.document_digest,
            self.scene_fingerprint,
            self.root_seed,
            self.bounds.min.u_m,
            self.bounds.min.v_m,
            self.bounds.max.u_m,
            self.bounds.max.v_m,
            self.pixels_per_metre,
            self.camera_digest,
            self.marks,
            self.crop_margin,
            self.blender_version,
            self.render_profile_digest,
            recipes,
            self.input.renderer,
            self.input.version,
            files(&self.input),
            self.target.renderer,
            self.target.version,
            files(&self.target),
            self.digest(),
        )
    }
}

/// A shard's directory layout.
///
/// ```text
/// 000001/
///   manifest.ron
///   input/beauty.png, material_weights.exr, elevation.exr, …
///   target/beauty.exr, albedo.exr, normal.exr, depth.exr, …
///   optional-scene/manifest.json, geometry files
/// ```
///
/// Two directories rather than a filename convention, because a training loader
/// enumerates one side at a time and a prefix match over a flat directory is
/// both slower and easy to get subtly wrong — `input-beauty.png` and
/// `input-beauty-2.png` sort adjacently and mean different things.
pub struct ShardLayout {
    pub root: std::path::PathBuf,
    pub shard: usize,
}

impl ShardLayout {
    pub fn new(root: impl Into<std::path::PathBuf>, shard: usize) -> Self {
        Self {
            root: root.into(),
            shard,
        }
    }

    /// This shard's own directory.
    pub fn directory(&self) -> std::path::PathBuf {
        self.root.join(format!("{:06}", self.shard))
    }

    pub fn manifest(&self) -> std::path::PathBuf {
        self.directory().join("manifest.ron")
    }

    pub fn input(&self, pass: &str, extension: &str) -> std::path::PathBuf {
        self.directory()
            .join("input")
            .join(format!("{pass}.{extension}"))
    }

    pub fn target(&self, pass: &str, extension: &str) -> std::path::PathBuf {
        self.directory()
            .join("target")
            .join(format!("{pass}.{extension}"))
    }

    /// Where the scene package goes, when one is kept.
    pub fn scene(&self) -> std::path::PathBuf {
        self.directory().join("optional-scene")
    }

    /// Create the directories a shard needs.
    pub fn create(&self) -> std::io::Result<()> {
        std::fs::create_dir_all(self.directory().join("input"))?;
        std::fs::create_dir_all(self.directory().join("target"))
    }
}

/// A checksum over a file's bytes.
pub fn checksum(bytes: &[u8]) -> Fingerprint {
    let mut digest = Digest::for_domain("terrain-dataset-file");
    digest.usize(bytes.len());
    for chunk in bytes.chunks(8) {
        let mut word = [0u8; 8];
        word[..chunk.len()].copy_from_slice(chunk);
        digest.u64(u64::from_le_bytes(word));
    }
    digest.finish()
}

#[cfg(test)]
mod tests {
    use super::*;
    use terrain_core::coords::WorldPoint;
    use terrain_scene::scene::{SceneBuilder, SceneRequest};

    fn scene() -> Arc<TerrainScene> {
        let request = SceneRequest::square(WorldPoint::ORIGIN, 4.0, 96.0);
        Arc::new(SceneBuilder::new(request, Fingerprint::from_u128(0x11), 1).build())
    }

    fn artifact(renderer: &str) -> RenderArtifact {
        RenderArtifact {
            renderer: renderer.into(),
            version: "0.1.0".into(),
            files: vec![ArtifactFile {
                pass: "beauty".into(),
                path: "beauty.png".into(),
                bytes: 4096,
                checksum: Fingerprint::from_u128(0x22),
            }],
        }
    }

    fn manifest(pair: &RenderPair) -> ShardManifest {
        ShardManifest {
            manifest_version: SHARD_MANIFEST_VERSION,
            shard: 1,
            document_digest: pair.scene().document_digest,
            scene_fingerprint: pair.scene_fingerprint(),
            root_seed: 0x8df7_82f9_5ce1_a4d4,
            bounds: pair.scene().request.bounds,
            pixels_per_metre: pair.scene().request.pixels_per_metre,
            camera_digest: Fingerprint::from_u128(0x33),
            input: pair.input.clone(),
            target: pair.target.clone(),
            blender_version: "5.2.0".into(),
            render_profile_digest: Fingerprint::from_u128(0x44),
            recipe_versions: vec![("population.grass_lush".into(), 1)],
            crop_margin: 96,
            marks: pair.scene().mark_count(),
        }
    }

    #[test]
    fn both_halves_of_a_pair_see_one_scene() {
        // The property the whole module exists to enforce, and it is enforced by
        // the type rather than by a rule: there is no constructor that takes two
        // scenes.
        let scene = scene();
        let seen: std::cell::RefCell<Vec<Fingerprint>> = std::cell::RefCell::new(Vec::new());
        let pair = RenderPair::render(
            Arc::clone(&scene),
            |s| {
                seen.borrow_mut().push(s.fingerprint());
                artifact("raster")
            },
            |s| {
                seen.borrow_mut().push(s.fingerprint());
                artifact("cycles")
            },
        );
        let seen = seen.into_inner();
        assert_eq!(seen.len(), 2);
        assert_eq!(seen[0], seen[1], "the two renderers saw different scenes");
        assert_eq!(pair.scene_fingerprint(), seen[0]);
    }

    #[test]
    fn a_manifest_pins_both_renderer_versions() {
        // A model whose targets came from two renderer versions has learned the
        // average of two looks, and nothing in a loss curve says so.
        let pair = RenderPair::render(scene(), |_| artifact("raster"), |_| artifact("cycles"));
        let base = manifest(&pair);
        let reference = base.digest();

        let mut moved = base.clone();
        moved.target.version = "0.2.0".into();
        assert_ne!(reference, moved.digest(), "the target's version");

        let mut input = base.clone();
        input.input.version = "0.2.0".into();
        assert_ne!(reference, input.digest(), "the input's version");

        let mut blender = base.clone();
        blender.blender_version = "6.0.0".into();
        assert_ne!(reference, blender.digest(), "the Blender version");

        let mut recipe = base.clone();
        recipe.recipe_versions[0].1 = 2;
        assert_ne!(reference, recipe.digest(), "the recipe version");

        let mut profile = base.clone();
        profile.render_profile_digest = Fingerprint::from_u128(0xffff);
        assert_ne!(reference, profile.digest(), "the render profile");

        let mut margin = base.clone();
        margin.crop_margin = 32;
        assert_ne!(reference, margin.digest(), "the crop margin");
    }

    #[test]
    fn a_manifest_serialises_to_readable_ron() {
        let pair = RenderPair::render(scene(), |_| artifact("raster"), |_| artifact("cycles"));
        let ron = manifest(&pair).to_ron();
        assert!(ron.starts_with("// One shard"));
        assert_eq!(ron.matches('(').count(), ron.matches(')').count(), "{ron}");
        assert_eq!(ron.matches('[').count(), ron.matches(']').count());
        for expected in [
            "scene_fingerprint:",
            "document_digest:",
            "blender_version: \"5.2.0\"",
            "crop_margin: 96",
            "manifest_digest:",
            "population.grass_lush",
        ] {
            assert!(ron.contains(expected), "{expected} is missing from:\n{ron}");
        }
    }

    #[test]
    fn a_shards_layout_keeps_the_two_sides_apart() {
        // Two directories rather than a filename convention: a training loader
        // enumerates one side at a time, and a prefix match over a flat
        // directory is both slower and easy to get subtly wrong.
        let layout = ShardLayout::new("target/corpus", 42);
        assert!(layout.directory().ends_with("000042"));
        assert!(layout.input("beauty", "png").ends_with("input/beauty.png"));
        assert!(
            layout
                .target("albedo", "exr")
                .ends_with("target/albedo.exr")
        );
        assert!(layout.manifest().ends_with("manifest.ron"));
        assert!(layout.scene().ends_with("optional-scene"));
    }

    #[test]
    fn a_checksum_catches_a_truncated_write() {
        // A short write is a black frame that nothing reports, and a length plus
        // a digest is the cheapest thing that turns it into an error.
        let full = vec![7u8; 1024];
        let short = vec![7u8; 1023];
        assert_ne!(checksum(&full), checksum(&short));
        assert_eq!(checksum(&full), checksum(&full));
        // And a change in the middle, not only at the end.
        let mut altered = full.clone();
        altered[512] = 8;
        assert_ne!(checksum(&full), checksum(&altered));
    }

    #[test]
    fn a_shard_records_how_much_grew_in_it() {
        // A crop from a nearly empty scene is not a hard example, it is a
        // useless one, and a corpus with a hundred of them has a hundred fewer
        // shards than its directory listing suggests.
        let pair = RenderPair::render(scene(), |_| artifact("raster"), |_| artifact("cycles"));
        assert_eq!(manifest(&pair).marks, pair.scene().mark_count());
    }
}
